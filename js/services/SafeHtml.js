class SafeHtml {
    // Safe only for text nodes and quoted HTML attributes; never use for JavaScript or CSS contexts.
    static escapeText(value) {
        return String(value ?? '')
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#39;');
    }
}
